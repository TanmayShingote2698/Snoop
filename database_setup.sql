-- Snoop System - Database Setup Script
-- Run this in your Supabase SQL Editor (https://app.supabase.com/)

-- 1. Create Admin Table
CREATE TABLE IF NOT EXISTS public.admin (
    admin_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    photo_url TEXT,
    password TEXT NOT NULL,
    tests_created JSONB DEFAULT '{"TestAmt":0}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Student Table
CREATE TABLE IF NOT EXISTS public.student (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    photo_url TEXT,
    password TEXT NOT NULL,
    tests_given JSONB DEFAULT '{"TestAmt":0}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Test Table
CREATE TABLE IF NOT EXISTS public.test (
    test_id TEXT PRIMARY KEY,
    test_details JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Create Result Table
CREATE TABLE IF NOT EXISTS public.result (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT,
    email TEXT NOT NULL,
    test_id TEXT NOT NULL,
    mcq_score INT DEFAULT 0,
    final_score INT DEFAULT 0,
    generated BOOLEAN DEFAULT FALSE,
    answers JSONB,
    integrity INT DEFAULT 0,
    tab_switch_data JSONB DEFAULT '[]'::jsonb,
    fullscreen_data JSONB DEFAULT '[]'::jsonb,
    action_logs JSONB DEFAULT '[]'::jsonb,
    subjective_score INT DEFAULT 0,
    -- AI Monitor Fields
    monitoring_enabled BOOLEAN DEFAULT FALSE,
    cheat_score DECIMAL(5,2) DEFAULT 0,
    combined_score DECIMAL(5,2) DEFAULT 0,
    risk_level TEXT DEFAULT 'LOW',
    anomaly_data JSONB DEFAULT '[]'::jsonb,
    monitoring_stats JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable RLS (Optional - Disable for dev)
ALTER TABLE public.admin ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.student ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.test ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.result ENABLE ROW LEVEL SECURITY;

-- Simple policy to allow all access for development (CHANGE IN PRODUCTION)
CREATE POLICY "Enable all for dev" ON public.admin FOR ALL USING (true);
CREATE POLICY "Enable all for dev" ON public.student FOR ALL USING (true);
CREATE POLICY "Enable all for dev" ON public.test FOR ALL USING (true);
CREATE POLICY "Enable all for dev" ON public.result FOR ALL USING (true);
